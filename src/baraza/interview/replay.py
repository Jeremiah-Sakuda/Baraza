"""BAR-330 AC 1 — the ``--replay`` harness.

The adaptation claim is the one claim in this project that a judge cannot check
by watching the demo. "The agent adapts" looks identical to "the agent has a
parameter named adapt". So the claim is discharged the only way it can be: by
committing raw transcripts of real runs and letting somebody else compute the
number from them.

**Input and output are deliberately different directories.**

``fixtures/interviews/<persona>.json``
    Hand-authored. What the departing officer says. This is a script, and it is
    supposed to be.

``fixtures/transcripts/<persona>.json``
    **Generated by an actual run of this module, and never hand-edited.** The
    harness overwrites the file wholesale on every run, so an edit survives
    exactly until the next run and shows up in the diff of the one after it.
    ``scripts/adaptation_metric.py`` reads these and imports nothing from this
    package, which is what makes the published number reproducible by someone
    who does not trust the application.

**Why the answers arrive on a timer.** An interview is paced by a person. A
harness that dumps twenty answers into the loop in four milliseconds is
exercising a different system than the one a judge watches — the streaming path
never has to hold anyone's attention, and a first-visible-token figure measured
under that load is a figure about nothing. The pace is declared per persona in
characters per minute, the run records whether it was paced and by what
acceleration factor, and any timing derived from a paced run says so.

**Why the two personas are shaped the way they are.** ``AdaptationState`` moves
the follow-up budget on the ratio of answers falling below
``TERSE_CHAR_THRESHOLD``. The terse persona sits entirely below it and drives the
budget up; the expansive persona sits entirely above it and drives the budget
down. That is checked at load time rather than assumed: a fixture that drifted
across the threshold would still produce a transcript, still produce a mean, and
mean nothing. :meth:`Persona.validate` refuses the run instead.

**Why the harness watches for exceptions the interviewer swallows.**
``Interviewer.compose_follow_up`` and ``Interviewer.check_divergence`` catch
everything and return ``None``. That is right for a live interview — losing one
clarifier is cheaper than hanging with a person waiting — and it is exactly
wrong for a transcript about to be published as evidence. A missing cassette
would otherwise yield a clean-looking run with zero follow-ups, a mean depth of
0.0, and no sign that the model was never consulted. So the client is wrapped:
every swallowed failure is recorded, the run aborts at the next turn boundary,
and no transcript is written. A number produced by silent failure is the same
defect as a number typed in by hand.
"""

