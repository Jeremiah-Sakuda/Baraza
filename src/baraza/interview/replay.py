"""The offline drive of a :class:`PartnerSession` — canned user turns on a timer.

The partner loop's claims — beliefs extracted per turn, collisions surfaced as
divergence cards, the blocked belief held out of the pool — are the ones a
judge cannot check by watching a live demo, because a live demo's inputs are
the team's. So the loop is exercised the only checkable way: a scripted set of
user turns drives the *real* ``PartnerSession`` — real extraction gates, real
contradiction detection, real append-only session store — and the run writes a
transcript that records, per turn, what was extracted, what was dropped and
why, and which collisions were raised.

**Input and output are deliberately different directories.**

``fixtures/interviews/<script>.json``
    Hand-authored. What the user types, turn by turn. This is a script, and it
    is supposed to be.

``fixtures/transcripts/<script>.json``
    **Generated by an actual run of this module, and never hand-edited.** The
    harness overwrites the file wholesale on every run, so an edit survives
    exactly until the next run and shows up in the diff of the one after it.
    Metric scripts read these and import nothing from this package, which is
    what makes any published number reproducible by someone who does not trust
    the application.

**Why the answers arrive on a timer.** A working session is paced by a person.
A harness that dumps twenty turns into the loop in four milliseconds is
exercising a different system than the one a person uses — the streaming path
never has to hold anyone's attention, and a first-visible-token figure measured
under that load is a figure about nothing. The pace is declared per script in
characters per minute, the run records whether it was paced and by what
acceleration factor, and any timing derived from a paced run says so.

**Why the harness watches for exceptions the session swallows.**
``Interviewer.compose_follow_up`` and ``PartnerSession._work_step`` catch
everything and degrade gracefully. That is right for a live session — losing
one clarifier is cheaper than hanging with a person waiting — and it is exactly
wrong for a transcript about to be published as evidence. A missing cassette
would otherwise yield a clean-looking run with zero follow-ups and no sign that
the model was never consulted. So the client is wrapped: every swallowed
failure is recorded, the run aborts, and no transcript is written. A number
produced by silent failure is the same defect as a number typed in by hand.
"""

